class Cidade:

    def __init__(
        self,
        nome,
        estado,
        populacao,
        chuva,
        nivel_rio,
        umidade
    ):
        self.nome = nome
        self.estado = estado
        self.populacao = populacao
        self.chuva = chuva
        self.nivel_rio = nivel_rio
        self.umidade = umidade